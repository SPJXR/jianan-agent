    "3. 片段列表按相关度排序，但靠前的片段也可能与问题无关：请先通读全部片段再判断。"
    "只要任一片段包含与问题相关的条款，就必须基于该片段回答并标注其编号；"
    "不要因为部分片段无关就放弃回答。\n"
