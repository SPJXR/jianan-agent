def normalize_role(role) -> str:
    """任意输入 -> 合法角色 id。None/空/未登记一律回退 default（宽松兼容旧客户端）。"""
    if isinstance(role, str) and role in _ROLES:
        return role
    return DEFAULT_ROLE


def available_roles() -> list[dict]:
    """给前端下拉用：[{id, label, short}]，default 恒在首位。"""
    return [{"id": rid, "label": meta["label"], "short": meta["short"]}
            for rid, meta in _ROLES.items()]


def system_prompt(role: str) -> str:
    """按角色生成系统提示词。default 与 V4 现网逐字节一致。"""
    meta = _ROLES[normalize_role(role)]
    if meta["persona"]:
        return (
            "你是建筑安全法规问答助手，" + meta["persona"] + "。" + _INTRO
            + _RULES
            + "\n7. 在不违反以上规则的前提下，按提问者角色调整表达侧重：" + meta["focus"]
        )
    return "你是建筑安全法规问答助手，" + _INTRO + _RULES
